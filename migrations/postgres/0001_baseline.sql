CREATE TABLE url_previews (
    url_id      BIGINT PRIMARY KEY REFERENCES urls (id) ON DELETE CASCADE,
    title       TEXT COLLATE "C",
    description TEXT COLLATE "C",
    image_url   TEXT COLLATE "C",
    image_key   TEXT COLLATE "C" UNIQUE,
    image_mime  TEXT COLLATE "C",
    image_data  BYTEA,
    CHECK (image_url IS NULL OR image_key IS NULL),
    CHECK ((image_key IS NULL AND image_mime IS NULL AND image_data IS NULL)
        OR (image_key IS NOT NULL AND image_mime IS NOT NULL AND image_data IS NOT NULL))
);

-- Remove a link's SNS preview (and its image) when the link is soft-deleted,
-- including account deletion; disabling or expiring a link keeps it.
CREATE FUNCTION url_previews_delete_with_link() RETURNS trigger
LANGUAGE plpgsql AS $$
BEGIN
    DELETE FROM url_previews WHERE url_id = NEW.id;
    RETURN NEW;
END;
$$;

CREATE TRIGGER url_previews_delete_with_link
AFTER UPDATE OF deleted_at ON urls
FOR EACH ROW
WHEN (OLD.deleted_at IS NULL AND NEW.deleted_at IS NOT NULL)
EXECUTE FUNCTION url_previews_delete_with_link();

CREATE TABLE public_creation_quota (
    scope        TEXT COLLATE "C" NOT NULL,
    period       TEXT COLLATE "C" NOT NULL CHECK (period IN ('minute', 'hour', 'day', 'week', 'month')),
    window_start BIGINT NOT NULL,
    window_end   BIGINT NOT NULL,
    used         BIGINT NOT NULL CHECK (used > 0),
    PRIMARY KEY (scope, period, window_start)
);
CREATE INDEX idx_public_creation_quota_end ON public_creation_quota (window_end);

