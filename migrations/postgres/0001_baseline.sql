-- urlet PostgreSQL baseline (SPEC FR-DB-4, §6.6).
--
-- Creates, in one transaction, the schema and seed data that SQLite reaches
-- after `migrations/0018_admin_url_lock.sql`. SQLite's upgrade steps are not
-- replayed: no PostgreSQL deployment predates them. Every later migration
-- ships as a pair with the same version name in `migrations/` and
-- `migrations/postgres/`, and `tests/postgres.rs` compares the two schemas.
--
-- Mapping rules:
--   * every SQLite INTEGER is BIGINT; 0/1 flags keep their CHECK constraints
--   * INTEGER PRIMARY KEY AUTOINCREMENT is a BIGINT identity column; seed rows
--     are inserted without ids, so each identity is already past them
--   * TEXT is TEXT COLLATE "C" (byte order, like SQLite's BINARY), so ISO
--     timestamps and keys compare identically whatever the database default
--   * TEXT COLLATE NOCASE is TEXT COLLATE nocase, an ICU nondeterministic
--     collation; SQL that says `COLLATE NOCASE` resolves to it unchanged
--   * BLOB is BYTEA; the SQLite trigger is a PL/pgSQL function plus trigger
--   * timestamps are ISO-8601 UTC text with milliseconds, as SQLite writes them

CREATE COLLATION IF NOT EXISTS nocase (provider = icu, locale = 'und-u-ks-level2', deterministic = false);

-- users, user_groups and domains reference each other in a cycle; the
-- references that close it are added once all three tables exist.

CREATE TABLE users (
    id                BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    email             TEXT COLLATE "C" NOT NULL,
    email_normalized  TEXT COLLATE "C" NOT NULL UNIQUE,
    password_hash     TEXT COLLATE "C" NOT NULL,
    display_name      TEXT COLLATE "C",
    role              TEXT COLLATE "C" NOT NULL DEFAULT 'user'   CHECK (role   IN ('user', 'admin')),
    status            TEXT COLLATE "C" NOT NULL DEFAULT 'active' CHECK (status IN ('active', 'suspended')),
    email_verified_at TEXT COLLATE "C",
    last_login_at     TEXT COLLATE "C",
    created_at        TEXT COLLATE "C" NOT NULL,
    updated_at        TEXT COLLATE "C" NOT NULL,
    deleted_at        TEXT COLLATE "C",
    group_id          BIGINT,
    is_system         BIGINT NOT NULL DEFAULT 0 CHECK (is_system IN (0, 1))
);
CREATE INDEX idx_users_role_status ON users (role, status);
CREATE INDEX idx_users_created_at  ON users (created_at DESC);
CREATE INDEX idx_users_group       ON users (group_id);
CREATE UNIQUE INDEX idx_users_single_system
    ON users (is_system) WHERE is_system = 1;

CREATE TABLE domains (
    id          BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    hostname    TEXT COLLATE "C" NOT NULL UNIQUE,
    is_default  BIGINT NOT NULL DEFAULT 0,
    is_verified BIGINT NOT NULL DEFAULT 0,
    created_by  BIGINT REFERENCES users (id) ON DELETE SET NULL,
    created_at  TEXT COLLATE "C" NOT NULL,
    status      TEXT COLLATE "C" NOT NULL DEFAULT 'active'
        CHECK (status IN ('pending', 'active', 'disabled')),
    source      TEXT COLLATE "C" NOT NULL DEFAULT 'ui'
        CHECK (source IN ('system', 'env', 'ui')),
    updated_at  TEXT COLLATE "C"
);
CREATE UNIQUE INDEX idx_domains_single_default
    ON domains (is_default) WHERE is_default = 1;
CREATE UNIQUE INDEX idx_domains_hostname_nocase
    ON domains (hostname COLLATE nocase);

CREATE TABLE user_groups (
    id                     BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    name                   TEXT COLLATE nocase NOT NULL UNIQUE,
    description            TEXT COLLATE "C",
    max_urls               BIGINT CHECK (max_urls IS NULL OR max_urls >= 0),
    max_api_tokens         BIGINT CHECK (max_api_tokens IS NULL OR max_api_tokens >= 0),
    allow_custom_slug      BIGINT NOT NULL DEFAULT 1 CHECK (allow_custom_slug IN (0, 1)),
    allow_password         BIGINT NOT NULL DEFAULT 1 CHECK (allow_password IN (0, 1)),
    allow_expiry           BIGINT NOT NULL DEFAULT 1 CHECK (allow_expiry IN (0, 1)),
    allow_max_clicks       BIGINT NOT NULL DEFAULT 1 CHECK (allow_max_clicks IN (0, 1)),
    allow_tags             BIGINT NOT NULL DEFAULT 1 CHECK (allow_tags IN (0, 1)),
    allow_api_tokens       BIGINT NOT NULL DEFAULT 1 CHECK (allow_api_tokens IN (0, 1)),
    allow_domain_selection BIGINT NOT NULL DEFAULT 1 CHECK (allow_domain_selection IN (0, 1)),
    is_default             BIGINT NOT NULL DEFAULT 0 CHECK (is_default IN (0, 1)),
    created_at             TEXT COLLATE "C" NOT NULL,
    updated_at             TEXT COLLATE "C" NOT NULL,
    default_domain_id      BIGINT REFERENCES domains (id) ON DELETE SET NULL,
    restrict_domains       BIGINT NOT NULL DEFAULT 0 CHECK (restrict_domains IN (0, 1)),
    max_invites            BIGINT CHECK (max_invites IS NULL OR max_invites >= 0),
    invite_period          TEXT COLLATE "C" NOT NULL DEFAULT 'month'
        CHECK (invite_period IN ('day', 'week', 'month')),
    allow_invites          BIGINT NOT NULL DEFAULT 0 CHECK (allow_invites IN (0, 1)),
    redirect_mode_policy   TEXT COLLATE "C" NOT NULL DEFAULT 'choice'
        CHECK (redirect_mode_policy IN ('direct', 'splash', 'choice'))
);
CREATE UNIQUE INDEX idx_user_groups_single_default
    ON user_groups (is_default) WHERE is_default = 1;

ALTER TABLE users
    ADD FOREIGN KEY (group_id) REFERENCES user_groups (id) ON DELETE SET NULL;

CREATE TABLE sessions (
    id           BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    user_id      BIGINT NOT NULL REFERENCES users (id) ON DELETE CASCADE,
    token_hash   TEXT COLLATE "C" NOT NULL UNIQUE,
    user_agent   TEXT COLLATE "C",
    ip_hash      TEXT COLLATE "C",
    created_at   TEXT COLLATE "C" NOT NULL,
    last_seen_at TEXT COLLATE "C" NOT NULL,
    expires_at   TEXT COLLATE "C" NOT NULL,
    revoked_at   TEXT COLLATE "C"
);
CREATE INDEX idx_sessions_user    ON sessions (user_id, expires_at);
CREATE INDEX idx_sessions_expires ON sessions (expires_at);

CREATE TABLE api_tokens (
    id           BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    user_id      BIGINT NOT NULL REFERENCES users (id) ON DELETE CASCADE,
    name         TEXT COLLATE "C" NOT NULL,
    token_prefix TEXT COLLATE "C" NOT NULL,
    token_hash   TEXT COLLATE "C" NOT NULL UNIQUE,
    scopes       TEXT COLLATE "C" NOT NULL DEFAULT '["urls:read","urls:write"]',
    last_used_at TEXT COLLATE "C",
    expires_at   TEXT COLLATE "C",
    created_at   TEXT COLLATE "C" NOT NULL,
    revoked_at   TEXT COLLATE "C"
);
CREATE INDEX idx_api_tokens_user ON api_tokens (user_id, created_at DESC);

CREATE TABLE urls (
    id                   BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    user_id              BIGINT NOT NULL REFERENCES users (id) ON DELETE CASCADE,
    domain_id            BIGINT NOT NULL REFERENCES domains (id) ON DELETE RESTRICT,
    slug                 TEXT COLLATE nocase NOT NULL,
    target_url           TEXT COLLATE "C" NOT NULL,
    title                TEXT COLLATE "C",
    notes                TEXT COLLATE "C",
    password_hash        TEXT COLLATE "C",
    expires_at           TEXT COLLATE "C",
    max_clicks           BIGINT CHECK (max_clicks IS NULL OR max_clicks > 0),
    click_count          BIGINT NOT NULL DEFAULT 0,
    unique_click_count   BIGINT NOT NULL DEFAULT 0,
    redirect_type        BIGINT NOT NULL DEFAULT 302
                         CHECK (redirect_type IN (301, 302, 307, 308)),
    status               TEXT COLLATE "C" NOT NULL DEFAULT 'active'
                         CHECK (status IN ('active', 'disabled')),
    is_custom_slug       BIGINT NOT NULL DEFAULT 0,
    last_clicked_at      TEXT COLLATE "C",
    created_at           TEXT COLLATE "C" NOT NULL,
    updated_at           TEXT COLLATE "C" NOT NULL,
    deleted_at           TEXT COLLATE "C",
    redirect_mode        TEXT COLLATE "C" NOT NULL DEFAULT 'direct'
        CHECK (redirect_mode IN ('direct', 'splash')),
    splash_delay_seconds BIGINT NOT NULL DEFAULT 5
        CHECK (splash_delay_seconds BETWEEN 1 AND 60),
    splash_title         TEXT COLLATE "C",
    splash_message       TEXT COLLATE "C",
    admin_disabled_at    TEXT COLLATE "C",
    UNIQUE (domain_id, slug)
);
CREATE INDEX idx_urls_user_created ON urls (user_id, created_at DESC);
CREATE INDEX idx_urls_created      ON urls (created_at DESC);
CREATE INDEX idx_urls_status       ON urls (status);
CREATE INDEX idx_urls_expires
    ON urls (expires_at) WHERE expires_at IS NOT NULL;

CREATE TABLE tags (
    id         BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    user_id    BIGINT NOT NULL REFERENCES users (id) ON DELETE CASCADE,
    name       TEXT COLLATE nocase NOT NULL,
    color      TEXT COLLATE "C",
    created_at TEXT COLLATE "C" NOT NULL,
    UNIQUE (user_id, name)
);

CREATE TABLE url_tags (
    url_id BIGINT NOT NULL REFERENCES urls (id) ON DELETE CASCADE,
    tag_id BIGINT NOT NULL REFERENCES tags (id) ON DELETE CASCADE,
    PRIMARY KEY (url_id, tag_id)
);
CREATE INDEX idx_url_tags_tag ON url_tags (tag_id);

CREATE TABLE clicks (
    id                 BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    url_id             BIGINT NOT NULL REFERENCES urls (id) ON DELETE CASCADE,
    clicked_at         TEXT COLLATE "C" NOT NULL,
    ip_hash            TEXT COLLATE "C",
    visitor_hash       TEXT COLLATE "C",
    user_agent         TEXT COLLATE "C",
    referrer           TEXT COLLATE "C",
    referrer_host      TEXT COLLATE "C",
    country_code       TEXT COLLATE "C",
    device_type        TEXT COLLATE "C",
    browser            TEXT COLLATE "C",
    os                 TEXT COLLATE "C",
    is_bot             BIGINT NOT NULL DEFAULT 0,
    is_unique          BIGINT NOT NULL DEFAULT 0,
    password_protected BIGINT NOT NULL DEFAULT 0
);
CREATE INDEX idx_clicks_url_time ON clicks (url_id, clicked_at DESC);
CREATE INDEX idx_clicks_time     ON clicks (clicked_at);
CREATE INDEX idx_clicks_visitor  ON clicks (url_id, visitor_hash);
CREATE INDEX idx_clicks_referrer ON clicks (url_id, referrer_host);
CREATE INDEX idx_clicks_bot      ON clicks (url_id, is_bot);

CREATE TABLE url_daily_stats (
    url_id        BIGINT NOT NULL REFERENCES urls (id) ON DELETE CASCADE,
    day           TEXT COLLATE "C" NOT NULL,
    clicks        BIGINT NOT NULL DEFAULT 0,
    unique_clicks BIGINT NOT NULL DEFAULT 0,
    bot_clicks    BIGINT NOT NULL DEFAULT 0,
    PRIMARY KEY (url_id, day)
);
CREATE INDEX idx_url_daily_stats_day ON url_daily_stats (day);

CREATE TABLE audit_logs (
    id            BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    actor_user_id BIGINT REFERENCES users (id) ON DELETE SET NULL,
    actor_role    TEXT COLLATE "C",
    action        TEXT COLLATE "C" NOT NULL,
    target_type   TEXT COLLATE "C",
    target_id     TEXT COLLATE "C",
    metadata      TEXT COLLATE "C",
